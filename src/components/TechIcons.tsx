export const getTechIcon = (type: string, className?: string) => {
  switch (type.toLowerCase()) {
    case 'java':
      return <JavaIcon className={className} />;
    case 'spring':
    case 'spring-boot':
      return <SpringIcon className={className} />;
    case 'react':
      return <ReactIcon className={className} />;
    case 'javascript':
    case 'js':
      return <JavascriptIcon className={className} />;
    case 'mysql':
      return <MysqlIcon className={className} />;
    case 'python':
      return <PythonIcon className={className} />;
    case 'git':
      return <GitIcon className={className} />;
    case 'aws':
      return <AwsIcon className={className} />;
    case 'tailwind':
    case 'tailwindcss':
      return <TailwindIcon className={className} />;
    default:
      return null;
  }
};
